import test from "node:test";
import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
const base=process.env.COMPUTE_TEST_API || "http://127.0.0.1:5195";
if (!["127.0.0.1","localhost"].includes(new URL(base).hostname)) throw Error("Acceptance tests are local-only.");
const nonce=randomBytes(5).toString("hex"), pass=randomBytes(24).toString("hex");
const model={vocab_size:257,width:32,layers:1,heads:4,expansion:2,context:64,tied:true};
async function call(path,token,body,status=200) {
  const r=await fetch(base+path,{method:body ? "POST" : "GET",headers:{...(token ? {Authorization:"Bearer "+token} : {}),...(body ? {"Content-Type":"application/json"} : {})},...(body ? {body:JSON.stringify(body)} : {})});
  const data=await r.json();assert.equal(r.status,status,data.error || `Unexpected HTTP status at ${path}`);return data;
}
test("real HTTP/D1: isolated teams, account roles, one-view keys and project coordination",async()=>{
  await call("/api/platform/me",null,null,401);
  const a=await call("/api/platform/setup",null,{username:"owner_a_"+nonce,password:pass,teamName:"Team A",project:{name:"Model A",model,targetTokens:100000}},201);
  const b=await call("/api/platform/setup",null,{username:"owner_b_"+nonce,password:pass,teamName:"Team B",project:{name:"Model B",model:{...model,layers:2},targetTokens:200000}},201);
  const c=await call("/api/platform/signup",null,{username:"contributor_"+nonce,password:pass},201);
  const ta=`/api/platform/teams/${a.teamId}`,pa=ta+`/projects/${a.projectId}`;
  assert.equal((await call("/api/platform/me",a.token)).teams.length,1);
  await call(ta,b.token,null,404);
  await call(pa,b.token,null,404);
  await call(ta+`/projects/${b.projectId}`,a.token,null,404);
  await call(ta+"/members",a.token,{accountId:a.user.id,role:"remove"},409);
  await call(ta+"/members",a.token,{accountId:a.user.id,role:"member"},409);
  const invitation=await call(ta+"/invitations",a.token,{},201);
  await call("/api/platform/join",c.token,{invite:invitation.invite});
  await call("/api/platform/join",b.token,{invite:invitation.invite},404);
  await call(ta+"/members",c.token,{accountId:c.user.id,role:"admin"},403);
  await call(ta+"/projects",c.token,{name:"Unauthorized project",model},403);
  const k=await call(ta+"/keys",c.token,{projectId:a.projectId,label:"CPU"},201);
  assert.equal((await call("/api/benchmark",k.key)).project.id,a.projectId);
  assert.ok(!JSON.stringify(await call(ta,c.token)).includes(k.key));
  const rotated=await call(ta+"/keys/"+k.id,c.token,{action:"rotate",generation:k.generation});
  await call("/api/benchmark",k.key,null,401);
  await call("/api/benchmark",rotated.key);
  assert.ok(!JSON.stringify(await call(ta,c.token)).includes(rotated.key));
  await call(ta+"/keys/"+k.id,c.token,{action:"rotate",generation:k.generation},409);
  await call(ta+"/keys/"+k.id,b.token,{action:"revoke"},404);
  await call(ta+"/members",a.token,{accountId:c.user.id,role:"admin"});
  const demotions=await Promise.all([fetch(base+ta+"/members",{method:"POST",headers:{Authorization:"Bearer "+a.token,"Content-Type":"application/json"},body:JSON.stringify({accountId:a.user.id,role:"member"})}),fetch(base+ta+"/members",{method:"POST",headers:{Authorization:"Bearer "+c.token,"Content-Type":"application/json"},body:JSON.stringify({accountId:c.user.id,role:"member"})})]);
  assert.deepEqual(demotions.map(r=>r.status).sort(),[200,409]);
  const afterRace=await call(ta,a.token);
  const survivor=afterRace.members.find(m=>m.role==="admin");
  assert.equal(afterRace.members.filter(m=>m.role==="admin").length,1);
  const survivorToken=survivor.account_id===a.user.id ? a.token : c.token;
  await call(ta+"/members",survivorToken,{accountId:a.user.id,role:"admin"});
  await call(ta+"/members",a.token,{accountId:c.user.id,role:"admin"});
  const external=await call(ta+"/projects",a.token,{name:"Different architecture",modelName:"Local adapter",runtime:"external",parameters:1000000000,context:2048,targetTokens:1000000000,adapterConfig:{architecture:"custom"}},201);
  const externalKey=await call(ta+"/keys",a.token,{projectId:external.id,label:"External model worker"},201);
  assert.equal((await call("/api/benchmark",externalKey.key)).project.parameters,1000000000);
  const creator=await call(ta+"/keys",a.token,{projectId:a.projectId,label:"Coordinator"},201);
  await call(pa+"/benchmark",a.token,{action:"configure",warmupSeconds:12,measureSeconds:34,batchTokens:768});
  const create=await call("/api/benchmark",creator.key,{action:"create",peers:["/ip4/127.0.0.1/tcp/40100/p2p/QmLocalFixture"]});
  assert.ok(create.id);
  const state=await call(pa+"/benchmark",a.token);
  assert.equal(state.session.config.model.width,32);
  assert.equal(state.session.config.payloadElements,16512);
  assert.equal(state.session.config.warmupSeconds,12);
  assert.equal(state.session.config.measureSeconds,34);
  assert.equal(state.session.config.batchTokens,768);
  assert.equal((await call(`/api/platform/teams/${b.teamId}/projects/${b.projectId}/benchmark`,b.token)).session,null);
  await call(pa+"/benchmark",a.token,{action:"start",sessionId:create.id},409);
  await call(pa+"/benchmark",a.token,{action:"configure",sessionId:create.id,warmupSeconds:0,measureSeconds:10,workload:"baseline-training",trainingProfile:"reference-fp32",microbatch:1,localSteps:1,batchTokens:512});
  const device={name:"Fixture CPU",kind:"cpu",platform:"Linux",torch:"2.8",workload:"baseline-training",workloadFingerprint:"a".repeat(64),batchTokens:512,trainingProfile:"reference-fp32",microbatch:1,localSteps:1};
  await call("/api/benchmark",rotated.key,{action:"register",sessionId:create.id,instanceId:"c".repeat(32),device});
  await call(pa+"/benchmark",a.token,{action:"configure",sessionId:create.id,batchTokens:768},409);
  await call(pa+"/benchmark",a.token,{action:"configure",sessionId:create.id,warmupSeconds:7,measureSeconds:25});
  const workerConfig=(await call("/api/benchmark",rotated.key)).session.config;
  assert.equal(workerConfig.warmupSeconds,7);
  assert.equal(workerConfig.measureSeconds,25);
  assert.equal(workerConfig.batchTokens,512);
  await call("/api/benchmark",rotated.key,{action:"request_ready",sessionId:create.id,instanceId:"c".repeat(32),ready:true});
  await call("/api/benchmark",rotated.key,{action:"heartbeat",sessionId:create.id,instanceId:"c".repeat(32),ready:true});
  await call(pa+"/benchmark",a.token,{action:"start",sessionId:create.id});
  assert.equal((await call(pa+"/benchmark",a.token)).session.phase,"countdown");
  await call(pa+"/benchmark",a.token,{action:"configure",sessionId:create.id,warmupSeconds:8},409);
  await call(pa+"/benchmark",a.token,{action:"cancel",sessionId:create.id});
  const next=await call("/api/benchmark",creator.key,{action:"create",peers:["/ip4/127.0.0.1/tcp/40100/p2p/QmLocalFixture"]});
  const nextState=await call("/api/benchmark",rotated.key);
  assert.equal(nextState.session.id,next.id);
  assert.deepEqual(nextState.session.config,workerConfig);
  await call(pa+"/benchmark",a.token,{action:"configure",sessionId:create.id,warmupSeconds:9},409);
  await call(pa+"/benchmark",a.token,{action:"configure",sessionId:next.id,trainingProfile:"optimized-fp16",localSteps:2},400);
  await call(pa+"/benchmark",a.token,{action:"configure",sessionId:next.id,trainingProfile:"optimized-fp16",localSteps:1});
  const fp16={...device,trainingProfile:"optimized-fp16"};
  await call("/api/benchmark",rotated.key,{action:"register",sessionId:next.id,instanceId:"e".repeat(32),device:fp16},400);
  await call("/api/benchmark",rotated.key,{action:"register",sessionId:next.id,instanceId:"e".repeat(32),device:{...fp16,kind:"rocm:0"}});
  await call("/api/benchmark",creator.key,{action:"register",sessionId:next.id,instanceId:"f".repeat(32),device:{...fp16,kind:"cuda:0"}});
  await call(pa+"/rooms",a.token,{action:"create",name:"Corpus run",fingerprint:"b".repeat(64),peer:"/ip4/127.0.0.1/tcp/40100/p2p/QmLocalFixture",shards:2});
  const room=(await call(pa+"/rooms",a.token)).room;
  await call("/api/rooms",rotated.key,{action:"join",roomId:room.id,instanceId:"d".repeat(32),name:"CPU",device:"cpu",fingerprint:room.fingerprint});
  await call("/api/rooms",rotated.key,{action:"ready",roomId:room.id,instanceId:"d".repeat(32),ready:true});
  await call(pa+"/rooms",a.token,{action:"start",roomId:room.id});
  assert.equal((await call(pa+"/rooms",a.token)).room.phase,"running");
  await call(pa+"/rooms",a.token,{action:"cancel",roomId:room.id});
  await call(ta+"/members",a.token,{accountId:c.user.id,role:"member"});
  await call(pa+"/benchmark",c.token,{action:"cancel",sessionId:next.id},403);
  await call(ta+"/members",a.token,{accountId:c.user.id,role:"remove"});
  await call("/api/benchmark",rotated.key,null,401);
  await call("/api/platform/logout",a.token,{});
  await call("/api/platform/me",a.token,null,401);
  const origin=await fetch(base+"/api/platform/me",{headers:{Origin:"https://untrusted.invalid",Authorization:"Bearer "+b.token}});
  assert.equal(origin.status,403);assert.equal(origin.headers.get("Access-Control-Allow-Origin"),null);
  console.log("Real SQLite-backed account/team/project/benchmark/room lifecycle passed; fixture passwords and keys were not printed.");
});
